import { defineConfig } from 'vite';
import { resolve } from 'path';
import { existsSync, readdirSync } from 'fs';
import jsnmContentPlugin from './scripts/vite-plugin-content.js';
import { GENERATED_DIRS } from './scripts/build-pages.js';

// Public website — multi-page Vite build. Root is public-site/.
// shared/ and content/ live one level up; server.fs.allow grants dev-server access.
const site = resolve(__dirname, 'public-site');

const TOP_LEVEL = [
  'index', 'about', 'doctors', 'doctor', 'conditions', 'condition', 'treatments', 'treatment',
  'services', 'lab', 'booking', 'faq', 'knowledge', 'knowledge-detail', 'testimonials', 'contact',
  'privacy', 'terms', 'medical-disclaimer', 'emergency'
];

function inputs() {
  const input = {};
  for (const name of TOP_LEVEL) {
    const f = resolve(site, `${name}.html`);
    if (existsSync(f)) input[name] = f;
  }
  // Pre-rendered detail pages generated by scripts/build-pages.js (run before `vite build`).
  for (const dir of GENERATED_DIRS) {
    const d = resolve(site, dir);
    if (!existsSync(d)) continue;
    for (const f of readdirSync(d)) {
      if (f.endsWith('.html')) input[`${dir}/${f.replace(/\.html$/, '')}`] = resolve(d, f);
    }
  }
  return input;
}

export default defineConfig({
  root: site,
  envDir: resolve(__dirname),
  appType: 'mpa',
  plugins: [jsnmContentPlugin()],
  server: { port: 5173, fs: { allow: [resolve(__dirname)] } },
  preview: { port: 5173 },
  build: {
    target: 'es2022',
    outDir: resolve(__dirname, 'dist'),
    emptyOutDir: true,
    rollupOptions: { input: inputs() }
  }
});
